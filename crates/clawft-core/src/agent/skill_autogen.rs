//! Autonomous skill creation (C4a).
//!
//! Detects repeated task patterns and auto-generates skill definitions.
//! Generated skills are installed in `~/.clawft/skills/` in a "pending"
//! state and require user approval before activation.
//!
//! **Review timing (WEFT-74 / ADR-080):** the canonical approval path is
//! CLI (`weft skills pending|approve|reject`). Interactive agent start may
//! print a non-blocking notice via [`pending_review_start_notice`]; a
//! blocking TTY prompt at loop start is **not** used.
//!
//! **Disabled by default** -- must be opted into via configuration.
//!
//! # Security
//!
//! Auto-generated skills have minimal permissions:
//! - No shell access
//! - No network access
//! - Filesystem limited to workspace directory (explicit allowlist in
//!   SKILL.md frontmatter; see [`SkillFilesystemAllowlist`])
//!
//! At load time the skill's filesystem allowlist is **intersected** with
//! the host agent's sandbox paths via
//! [`effective_filesystem_on_load`]. The effective set never exceeds the
//! host (WEFT-75).
//!
//! # Pattern Detection
//!
//! The detector tracks sequences of tool calls. When the same sequence
//! appears at least `threshold` times (default: 3), a skill candidate
//! is generated.

