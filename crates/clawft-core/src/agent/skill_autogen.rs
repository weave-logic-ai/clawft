// ---------------------------------------------------------------------------
// Filesystem allowlist (WEFT-75)
// ---------------------------------------------------------------------------

/// Workspace-relative path used as the minimal autogen FS root.
///
/// Matches the design target "filesystem limited to workspace directory".
pub const AUTOGEN_WORKSPACE_PATH: &str = ".";

/// Frontmatter key under which the filesystem allowlist is emitted/parsed.
pub const FILESYSTEM_FRONTMATTER_KEY: &str = "filesystem";

/// Explicit filesystem allowlist for a skill (SKILL.md `filesystem:` block).
///
/// Autogenerated skills always emit a **minimal** instance of this struct
/// via [`SkillFilesystemAllowlist::minimal_autogen`]. At load time the
/// skill's allowlist is intersected with the host agent so the effective
/// permissions never exceed either side.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SkillFilesystemAllowlist {
    /// Paths the skill may read (relative or absolute).
    pub readable_paths: Vec<String>,
    /// Paths the skill may write.
    pub writable_paths: Vec<String>,
    /// Whether new files may be created under writable paths.
    pub allow_create: bool,
    /// Whether files may be deleted under writable paths.
    pub allow_delete: bool,
}

impl Default for SkillFilesystemAllowlist {
    fn default() -> Self {
        Self::minimal_autogen()
    }
}

impl SkillFilesystemAllowlist {
    /// Minimal allowlist for autogenerated skills.
    ///
    /// - Read/write limited to the workspace root (`.`)
    /// - No create / delete
    pub fn minimal_autogen() -> Self {
        Self {
            readable_paths: vec![AUTOGEN_WORKSPACE_PATH.into()],
            writable_paths: vec![AUTOGEN_WORKSPACE_PATH.into()],
            allow_create: false,
            allow_delete: false,
        }
    }

    /// Render as a YAML frontmatter fragment (no leading/trailing `---`).
    ///
    /// Example:
    /// ```text
    /// filesystem:
    ///   readable-paths:
    ///     - .
    ///   writable-paths:
    ///     - .
    ///   allow-create: false
    ///   allow-delete: false
    /// ```
    pub fn to_yaml_frontmatter(&self) -> String {
        let mut out = String::from("filesystem:\n");
        out.push_str("  readable-paths:\n");
        if self.readable_paths.is_empty() {
            out.push_str("    []\n");
        } else {
            for p in &self.readable_paths {
                out.push_str(&format!("    - {p}\n"));
            }
        }
        out.push_str("  writable-paths:\n");
        if self.writable_paths.is_empty() {
            out.push_str("    []\n");
        } else {
            for p in &self.writable_paths {
                out.push_str(&format!("    - {p}\n"));
            }
        }
        out.push_str(&format!("  allow-create: {}\n", self.allow_create));
        out.push_str(&format!("  allow-delete: {}\n", self.allow_delete));
        out
    }

    /// Parse from a JSON value (as stored in [`SkillDefinition::metadata`]).
    ///
    /// Accepts both kebab-case (`readable-paths`) and snake_case keys.
    pub fn from_json(value: &serde_json::Value) -> Option<Self> {
        let obj = value.as_object()?;
        let readable = string_list_from_map(obj, "readable-paths")
            .or_else(|| string_list_from_map(obj, "readable_paths"))
            .unwrap_or_default();
        let writable = string_list_from_map(obj, "writable-paths")
            .or_else(|| string_list_from_map(obj, "writable_paths"))
            .unwrap_or_default();
        let allow_create = bool_from_map(obj, "allow-create")
            .or_else(|| bool_from_map(obj, "allow_create"))
            .unwrap_or(false);
        let allow_delete = bool_from_map(obj, "allow-delete")
            .or_else(|| bool_from_map(obj, "allow_delete"))
            .unwrap_or(false);
        Some(Self {
            readable_paths: readable,
            writable_paths: writable,
            allow_create,
            allow_delete,
        })
    }

    /// Extract the filesystem allowlist from a loaded skill.
    ///
    /// Looks up `metadata["filesystem"]`. For autogenerated skills that
    /// lack an explicit block (legacy), falls back to
    /// [`Self::minimal_autogen`]. Returns `None` for non-autogen skills
    /// without a `filesystem` block.
    pub fn from_skill(skill: &SkillDefinition) -> Option<Self> {
        if let Some(value) = skill.metadata.get(FILESYSTEM_FRONTMATTER_KEY) {
            return Self::from_json(value);
        }
        if is_autogenerated_skill(skill) {
            return Some(Self::minimal_autogen());
        }
        None
    }

    /// Whether this allowlist does not exceed `other`.
    ///
    /// - Empty path lists on `other` mean unrestricted (same as
    ///   [`intersect_path_allowlists`]): any self paths are allowed.
    /// - Non-empty `other` lists require every self path to be a member.
    /// - Boolean flags on self may only be true if `other` also allows them.
    ///
    /// Used to assert the effective set never exceeds the host.
    pub fn is_subset_of(&self, other: &Self) -> bool {
        let read_ok = other.readable_paths.is_empty()
            || self
                .readable_paths
                .iter()
                .all(|p| other.readable_paths.iter().any(|h| paths_equal(p, h)));
        let write_ok = other.writable_paths.is_empty()
            || self
                .writable_paths
                .iter()
                .all(|p| other.writable_paths.iter().any(|h| paths_equal(p, h)));
        let create_ok = !self.allow_create || other.allow_create;
        let delete_ok = !self.allow_delete || other.allow_delete;
        read_ok && write_ok && create_ok && delete_ok
    }
}

fn string_list_from_map(
    obj: &serde_json::Map<String, serde_json::Value>,
    key: &str,
) -> Option<Vec<String>> {
    let arr = obj.get(key)?.as_array()?;
    Some(
        arr.iter()
            .filter_map(|v| v.as_str().map(String::from))
            .collect(),
    )
}

fn bool_from_map(obj: &serde_json::Map<String, serde_json::Value>, key: &str) -> Option<bool> {
    obj.get(key)?.as_bool()
}

fn paths_equal(a: &str, b: &str) -> bool {
    let na = if a == "/" {
        a.to_string()
    } else {
        a.trim_end_matches('/').to_string()
    };
    let nb = if b == "/" {
        b.to_string()
    } else {
        b.trim_end_matches('/').to_string()
    };
    na == nb
}

/// Whether a skill was produced by the autogen pipeline.
///
/// True when frontmatter set `autogenerated: true` (stored in metadata).
pub fn is_autogenerated_skill(skill: &SkillDefinition) -> bool {
    skill
        .metadata
        .get("autogenerated")
        .and_then(|v| v.as_bool())
        .unwrap_or(false)
}

/// Intersect a skill's filesystem allowlist with the host agent's.
///
/// - Path lists use [`intersect_path_allowlists`] (skill ∩ host when both
///   non-empty; empty side defers to the other).
/// - Boolean flags are AND'd so the skill cannot escalate create/delete.
///
/// The result is always a subset of the host when the host paths are
/// non-empty (path membership) and never grants a flag the host denies.
pub fn intersect_filesystem_allowlist(
    skill: &SkillFilesystemAllowlist,
    host: &SkillFilesystemAllowlist,
) -> SkillFilesystemAllowlist {
    SkillFilesystemAllowlist {
        readable_paths: intersect_path_allowlists(&skill.readable_paths, &host.readable_paths),
        writable_paths: intersect_path_allowlists(&skill.writable_paths, &host.writable_paths),
        allow_create: skill.allow_create && host.allow_create,
        allow_delete: skill.allow_delete && host.allow_delete,
    }
}

/// Resolve the effective filesystem allowlist when loading a skill under
/// a host agent sandbox (WEFT-75 load-time intersection).
///
/// 1. Extract the skill's declared allowlist from metadata (or minimal
///    defaults for autogenerated skills).
/// 2. Intersect with `host`.
/// 3. Return the effective set (never exceeds host when host is non-empty).
///
/// For non-autogen skills without a `filesystem` block, returns a clone
/// of `host` (no additional restriction beyond the agent sandbox).
pub fn effective_filesystem_on_load(
    skill: &SkillDefinition,
    host: &SkillFilesystemAllowlist,
) -> SkillFilesystemAllowlist {
    match SkillFilesystemAllowlist::from_skill(skill) {
        Some(skill_fs) => intersect_filesystem_allowlist(&skill_fs, host),
        None => host.clone(),
    }
}

